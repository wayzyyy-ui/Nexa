-- ─────────────────────────────────────────────────────────────────────────────
-- NEXA: «Закреплено» в истории диалогов — колонка pinned в таблице chats.
--
-- Как запустить: Supabase → SQL Editor → вставить файл целиком → Run.
-- Можно запускать повторно: если колонка уже есть, ничего не изменится.
--
-- Что делает:
--   • добавляет колонку pinned (да/нет), по умолчанию — нет (false).
--     Существующие диалоги остаются как были, просто не закреплены.
--   • Новую таблицу не создаёт, данные не удаляет.
--
-- Доступ не меняется: правила RLS у chats действуют на всю строку
-- («только свои строки», см. sync-tables.sql), а права authenticated
-- даны на всю таблицу — новая колонка под ними автоматически.
--
-- До запуска этого файла приложение работает как раньше: закрепление
-- хранится только в браузере и в облако не уходит.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.chats
  add column if not exists pinned boolean not null default false;

-- Чтобы API Supabase сразу увидел новую колонку (без ожидания)
notify pgrst, 'reload schema';

-- Проверка (только чтение): должна вернуться одна строка pinned | boolean | NO | false
select column_name, data_type, is_nullable, column_default
from information_schema.columns
where table_schema = 'public' and table_name = 'chats' and column_name = 'pinned';
