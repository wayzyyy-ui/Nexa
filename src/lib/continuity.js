/* Продолжение работы на другом устройстве (Continuity).
   Своей связи нет — тот же канал nexa:<uid> и события continue.* (схемы — realtime.js).
   Ход: отправитель → continue.offer { id, to_device, kind, ref, exp } → получатель находит объект
   В СВОЁМ аккаунте (диалог — в chats, файл — в files, загруженный в облако) и показывает карточку
   «Продолжить?» → continue.reply: shown (показали) → opened / declined / missing / expired / busy.
   Содержимое диалогов и файлов по каналу не идёт — только вид и номер.
   Ничего не открывается само: только после «Открыть» на том устройстве */

export const CONT_TTL_MS = 2 * 60 * 1000; // предложение живёт 2 минуты
export const CONT_ACK_MS = 10 * 1000;     // не показали за 10 с — «не ответило»
export const CONT_CONNECT_MS = 10 * 1000; // ждём канал связи не дольше 10 с

// Стадии у отправителя: подключение → передача → ждём на устройстве → открыто / не удалось
export const CONT_STAGE = {
  connecting: "Подключение…",
  sending: "Передача…",
  shown: "Передано — ждём, пока откроют на устройстве",
  opened: "Открыто",
  failed: "Не удалось",
};
export const CONT_FAIL = {
  offline: "Нет связи с сервером — проверьте интернет",
  send: "Не получилось отправить — попробуйте ещё раз",
  noanswer: "Устройство не ответило — откройте NEXA на нём и повторите",
  left: "Устройство отключилось",
  declined: "На устройстве нажали «Не сейчас»",
  missing: "На том устройстве этого пока нет — данные ещё не синхронизировались. Повторите через минуту",
  expired: "Время вышло — предложение действовало 2 минуты",
  busy: "На устройстве уже открыто другое предложение",
};
export const contDone = (status) => status === "opened" || status === "failed";

// Что предлагаем — подпись для людей. Имя берёт каждая сторона из своих данных
export const contWhat = (kind, title) => (kind === "chat" ? `Диалог «${title || "Без названия"}»` : `Файл «${title || "без имени"}»`);

// Срок предложения правдоподобен: ещё не вышел и не дальше, чем позволяет TTL (+ запас на разницу часов)
export const contFresh = (exp, now = Date.now()) => exp > now && exp - now <= CONT_TTL_MS + 30000;
