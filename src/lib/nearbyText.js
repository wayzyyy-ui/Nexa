// Сколько осталось видимым: «9 мин» / «40 с»
export function leftText(ms) {
  if (ms <= 0) return "0 с";
  return ms >= 60000 ? `${Math.ceil(ms / 60000)} мин` : `${Math.ceil(ms / 1000)} с`;
}

